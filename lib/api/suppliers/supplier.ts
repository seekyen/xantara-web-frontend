import { apiFetch, type PagedResponse } from '../client'

export type SupplierType = 'manufacturer' | 'distributor' | 'local' | 'imported'

export const SUPPLIER_TYPES: SupplierType[] = ['manufacturer', 'distributor', 'local', 'imported']
export const PAYMENT_TERMS   = ['COD', 'Net 15', 'Net 30', 'Net 60', 'Net 90']
export const PAYMENT_METHODS = ['Bank Transfer', 'Check', 'Cash']
export const CURRENCIES      = ['PHP', 'USD', 'EUR', 'JPY']

export interface Supplier {
  id:                        number
  supplier_code:             string
  company_name:              string
  trade_name:                string | null
  legal_name:                string | null
  tin:                       string | null
  business_permit_no:        string | null
  is_vat_registered:         boolean
  payment_terms:             string
  preferred_payment_method:  string | null
  currency:                  string
  lead_time_days:            number
  minimum_order_quantity:    number
  supplier_type:             SupplierType
  is_active:                 boolean
  is_accredited:             boolean
  rating:                    string | null
  created_at:                string
  created_by:                number | null
  updated_at:                string
  updated_by:                number | null
}

export type SupplierWriteData = {
  supplier_code: string
  company_name:  string
} & Partial<Omit<Supplier, 'id' | 'supplier_code' | 'company_name' | 'created_at' | 'created_by' | 'updated_at' | 'updated_by'>>

export interface SuppliersParams {
  supplier_type?:      SupplierType
  is_active?:          boolean
  is_accredited?:      boolean
  is_vat_registered?:  boolean
  search?:             string
  ordering?:           string
  page?:               number
}

export async function getSuppliersPage(params: SuppliersParams = {}, token?: string): Promise<PagedResponse<Supplier>> {
  const query = new URLSearchParams()
  if (params.supplier_type)     query.set('supplier_type', params.supplier_type)
  if (params.is_active !== undefined)         query.set('is_active', String(params.is_active))
  if (params.is_accredited !== undefined)     query.set('is_accredited', String(params.is_accredited))
  if (params.is_vat_registered !== undefined) query.set('is_vat_registered', String(params.is_vat_registered))
  if (params.search)   query.set('search', params.search)
  if (params.ordering) query.set('ordering', params.ordering)
  if (params.page)     query.set('page', String(params.page))

  const qs = query.toString()
  return apiFetch<PagedResponse<Supplier>>(`/api/v1/suppliers/${qs ? `?${qs}` : ''}`, {}, token)
}

export const getSupplier = (id: number, token?: string) =>
  apiFetch<Supplier>(`/api/v1/suppliers/${id}/`, {}, token)

/** Follows pagination to fetch every supplier — used to compute the next auto-generated
 *  supplier_code (supplier_code is NOT auto-generated by the backend; the frontend must
 *  supply one), by scanning for the highest "SUP-####" number already in use. */
export async function getAllSuppliers(token?: string): Promise<Supplier[]> {
  const all: Supplier[] = []
  let page = 1
  let hasNext = true
  while (hasNext) {
    const data = await getSuppliersPage({ page }, token)
    all.push(...data.results)
    hasNext = data.next !== null
    page++
  }
  return all
}

export const createSupplier = (data: SupplierWriteData, token?: string) =>
  apiFetch<Supplier>('/api/v1/suppliers/', { method: 'POST', body: JSON.stringify(data) }, token)

export const updateSupplier = (id: number, data: Partial<SupplierWriteData>, token?: string) =>
  apiFetch<Supplier>(`/api/v1/suppliers/${id}/`, { method: 'PATCH', body: JSON.stringify(data) }, token)

/** Soft-delete: sets is_active false, returns the updated object (not 204) — used for the
 *  rollback path when a sub-resource (Address/Contact/BankDetail/ProductCategory) create
 *  fails right after this Supplier was created. */
export const deleteSupplier = (id: number, token?: string) =>
  apiFetch<Supplier>(`/api/v1/suppliers/${id}/`, { method: 'DELETE' }, token)
